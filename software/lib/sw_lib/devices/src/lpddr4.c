// Functions called by the generated PHY init sequence (same interface as the
// subsystem's sw/libs/phyinit_template.c, adapted to memory-mapped access)
//-----------------------------------------------------------------------------
// Progress: the PHY init is ~18,000 writes and prints nothing on its own, so
// report every 1000 writes (a quiet log then always means "stuck", not "busy").
static unsigned phy_writes = 0;

void dwc_ddrphy_apb_wr(unsigned int addr, unsigned int data)
{
  apb4_write(addr << 2, data);
  if ((++phy_writes % 1000u) == 0u)
    printf("PHY writes: %u\n", phy_writes);
}

