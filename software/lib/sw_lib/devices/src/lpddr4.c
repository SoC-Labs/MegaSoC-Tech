#include <stdio.h>
#include <stdint.h>

#define POLL_LIMIT  LPDDR4_POLL_LIMIT
#define POLL_REPORT 256   // status line every POLL_REPORT polls shows liveness

static int errors_total = 0;
static int prog_errors  = 0;

//-----------------------------------------------------------------------------
// Register access, same names as the standalone flow (apb3 = controller side,
// apb4 = PHY side; addresses are the APB byte addresses used there)
//-----------------------------------------------------------------------------
static inline void apb3_write(uint32_t addr, uint32_t data)
{
  *(volatile uint32_t *)(LPDDR4_CTRL_BASE + addr) = data;
}
static inline void apb3_read(uint32_t addr, uint32_t *data)
{
  *data = *(volatile uint32_t *)(LPDDR4_CTRL_BASE + addr);
}
static inline void apb4_write(uint32_t addr, uint32_t data)
{
  *(volatile uint32_t *)(LPDDR4_PHY_BASE + addr) = data;
}
static inline void apb4_read(uint32_t addr, uint32_t *data)
{
  *data = *(volatile uint32_t *)(LPDDR4_PHY_BASE + addr);
}

static void apb3_bit_set(uint32_t addr, uint32_t bit)
{
  uint32_t reg;
  apb3_read(addr, &reg);
  apb3_write(addr, reg | (1u << bit));
}
static void apb3_bit_clear(uint32_t addr, uint32_t bit)
{
  uint32_t reg;
  apb3_read(addr, &reg);
  apb3_write(addr, reg & ~(1u << bit));
}

// Write a controller register and read it back
static void prog_reg(const char *name, uint32_t addr, uint32_t val)
{
  uint32_t rb;
  apb3_write(addr, val);
  apb3_read(addr, &rb);
  printf("REGPROG %-10s 0x%03x <= 0x%08x readback 0x%08x%s\n",
         name, (unsigned)addr, (unsigned)val, (unsigned)rb, (rb == val) ? "" : "  MISMATCH");
  if (rb != val) prog_errors++;
}

// Poll a register until (value & mask) == want; 0 on success, 1 on timeout
static int poll_ctrl(const char *what, uint32_t addr, uint32_t mask, uint32_t want)
{
  uint32_t v = 0;
  for (int i = 0; i < POLL_LIMIT; i++) {
    apb3_read(addr, &v);
    if ((v & mask) == want) return 0;
    if (i && (i % POLL_REPORT) == 0)
      printf("  waiting for %s: 0x%08x after %d polls\n", what, (unsigned)v, i);
  }
  printf("ERROR: timeout waiting for %s (reg 0x%03x = 0x%08x)\n", what, (unsigned)addr, (unsigned)v);
  errors_total++;
  return 1;
}
static int poll_phy(const char *what, uint32_t addr, uint32_t mask, uint32_t want)
{
  uint32_t v = 0;
  for (int i = 0; i < POLL_LIMIT; i++) {
    apb4_read(addr, &v);
    if ((v & mask) == want) return 0;
    if (i && (i % POLL_REPORT) == 0)
      printf("  waiting for %s: 0x%08x after %d polls\n", what, (unsigned)v, i);
  }
  printf("ERROR: timeout waiting for %s (PHY 0x%06x = 0x%08x)\n", what, (unsigned)addr, (unsigned)v);
  errors_total++;
  return 1;
}

