//-----------------------------------------------------------------------------
// Controller + PHY initialisation (same order and values as the standalone
// dram_tests.c on lpddr4_subsystem main). Returns 0 on success.
//-----------------------------------------------------------------------------
int lpddr4_init(void)
{
  uint32_t tmp;

  if (!LPDDR4_PHYINIT_PRESENT) {
    printf("ERROR: PHY init sequence not generated -- run\n"
           "       make -C $LPDDR4_PROJECT_DIR build_phyinit, then rebuild the test\n");
    errors_total++;
    return 1;
  }

  printf("** Start DDR controller init **\n");
  // Hold core reset, hold APB reset, enable clocks, release APB reset
  for (int i = 0; i < 32;  i++) apb3_write(0x6008, 0x0);
  for (int i = 0; i < 32;  i++) apb3_write(0x600C, 0x0);
  apb3_write(0x6010, 0x1);
  for (int i = 0; i < 128; i++) apb3_write(0x6014, 0x1);
  for (int i = 0; i < 256; i++) apb3_write(0x600C, 0x1);

  // MSTR: LPDDR4, BL16 (static, written while the core is in reset)
  prog_reg("MSTR",      0x000, 0x00080020);

  // Timing for LPDDR4-1600 x16 (values and derivation: standalone dram_tests.c)
  prog_reg("DRAMTMG0",  0x100, 0x11101b11);
  prog_reg("DRAMTMG1",  0x104, 0x0004041a);
  prog_reg("DRAMTMG2",  0x108, 0x04070a0d);
  prog_reg("DRAMTMG3",  0x10c, 0x0050600c);
  prog_reg("DRAMTMG4",  0x110, 0x08040409);
  prog_reg("DRAMTMG5",  0x114, 0x05050603);
  prog_reg("DRAMTMG14", 0x138, 0x00000037);
  prog_reg("DFITMG0",   0x190, 0x07898204);
  prog_reg("DFITMG1",   0x194, 0x001f0404);
  prog_reg("DFITMG2",   0x1b4, 0x00000904);
  prog_reg("RFSHTMG",   0x064, 0x00300034);

  // Mode-register copies (must match what the PHY init programs)
  prog_reg("INIT3",     0x0dc, 0x00240012);
  prog_reg("INIT4",     0x0e0, 0x00090028);   // MR13 DMD=1: data mask off
  prog_reg("INIT6",     0x0e8, 0x0033002b);
  prog_reg("INIT7",     0x0ec, 0x0018002b);
  prog_reg("DBICTL",    0x1c0, 0x00000000);

  // Address map: column = byte[10:1], bank = byte[13:11], row = byte[27:14]
  prog_reg("ADDRMAP1",  0x204, 0x00080808);
  prog_reg("ADDRMAP2",  0x208, 0x00000000);
  prog_reg("ADDRMAP3",  0x20c, 0x00000000);
  prog_reg("ADDRMAP4",  0x210, 0x00001f1f);
  prog_reg("ADDRMAP5",  0x214, 0x07070707);
  prog_reg("ADDRMAP6",  0x218, 0x0f0f0707);
  prog_reg("ADDRMAP7",  0x21c, 0x00000f0f);
  printf("REGPROG done, %d readback mismatch(es)\n", prog_errors);

  // DRAM init by the PHY (training) or, in simulation-only mode, by the controller
  printf("STEP INIT0/PWRCTL (0x0d0, 0x030)\n");
  if (LPDDR4_SKIP_TRAINING) {
    apb3_bit_clear(0x0d0, 30);
    apb3_bit_clear(0x0d0, 31);
    apb3_bit_clear(0x030, 5);
  } else {
    apb3_bit_set(0x0d0, 30);
    apb3_bit_set(0x0d0, 31);
    apb3_bit_set(0x030, 5);
  }

  // No self-refresh / power-down / DRAM clock stop during init
  printf("STEP RFSHCTL3/PWRCTL (0x060, 0x030)\n");
  apb3_bit_set(0x060, 0);
  apb3_bit_clear(0x030, 1);
  apb3_bit_clear(0x030, 0);
  apb3_bit_clear(0x030, 3);

  printf("STEP SWCTL (0x320)\n");
  apb3_bit_clear(0x320, 0);                      // SWCTL.sw_done = 0
  // No sw_done_ack poll here: that is only needed when the controller's
  // on-chip parity feature (OCCAP) is enabled, and this controller build does
  // not have it -- its OCCAPCCFG register (0x3e0) does not exist and a read
  // returns an APB error (bus abort on the A53). The standalone testbench's APB
  // driver ignored that error and read 0, so it skipped the poll too.
  printf("STEP DFIMISC/SWCTL/SWSTAT (0x1b0, 0x320, 0x324)\n");
  apb3_bit_clear(0x1b0, 0);                      // DFIMISC.dfi_init_complete_en = 0
  apb3_bit_set(0x320, 0);                        // SWCTL.sw_done = 1
  if (poll_ctrl("SWSTAT.sw_done_ack", 0x324, 0x1, 0x1)) return 1;

  printf("STEP release core reset (0x6008)\n");
  for (int i = 0; i < 32; i++) apb3_write(0x6008, 0x1);   // release core reset

  printf("** Start DDR PHY init **\n");
  phyinit();
  printf("** Finish DDR PHY init (%u PHY writes) **\n", phy_writes);
  if (errors_total) return 1;

  printf("STEP wait PHY calibration done (0x8025c)\n");
  if (poll_phy("PHY calibration (CalBusy=0)", 0x8025c, 0xFFFFFFFF, 0x0)) return 1;

  apb3_bit_clear(0x320, 0);                      // no OCCAP in this build (see above)
  printf("STEP DFI init start + wait dfi_init_complete (0x1b0, 0x1bc)\n");
  apb3_bit_set(0x1b0, 5);                        // DFIMISC.dfi_init_start = 1
  apb3_bit_set(0x320, 0);
  if (poll_ctrl("SWSTAT.sw_done_ack", 0x324, 0x1, 0x1)) return 1;
  if (poll_ctrl("DFISTAT.dfi_init_complete", 0x1bc, 0x1, 0x1)) return 1;

  printf("STEP DFI init done, enable normal operation\n");
  apb3_bit_clear(0x320, 0);
  apb3_bit_clear(0x1b0, 5);                      // dfi_init_start = 0
  apb3_bit_set(0x1b0, 0);                        // dfi_init_complete_en = 1
  apb3_bit_clear(0x030, 5);                      // PWRCTL.selfref_sw = 0
  apb3_bit_set(0x320, 0);
  if (poll_ctrl("SWSTAT.sw_done_ack", 0x324, 0x1, 0x1)) return 1;

  printf("STEP wait controller normal mode / DRAM init (STAT 0x004)\n");
  if (poll_ctrl("STAT.operating_mode == normal", 0x004, 0x7, 0x1)) return 1;

  // Normal operation: auto-refresh, power-down, self-refresh, clock stop on
  apb3_bit_clear(0x060, 0);
  apb3_bit_set(0x030, 1);
  apb3_bit_set(0x030, 0);
  apb3_bit_set(0x030, 3);
  apb3_write(0x490, 1);                          // PCTRL_0: enable AXI port 0

  apb3_read(0x004, &tmp);
  printf("STAT = 0x%08x, DRAM ready\n", (unsigned)tmp);
  return prog_errors ? 1 : 0;
}

//-----------------------------------------------------------------------------
// DRAM access through the CPU
//-----------------------------------------------------------------------------
void lpddr4_cache_clean_invalidate(uintptr_t addr, uintptr_t len)
{
  uintptr_t a = addr & ~(uintptr_t)(LPDDR4_CACHE_LINE - 1);
  for (; a < addr + len; a += LPDDR4_CACHE_LINE)
    __asm__ volatile ("dc civac, %0" : : "r"(a) : "memory");
  __asm__ volatile ("dsb sy" ::: "memory");
  __asm__ volatile ("isb" ::: "memory");
}


int lpddr4_report_mismatch(const char *t, int errs, uintptr_t off, uint64_t got, uint64_t exp)
{
  if (errs < 10)
    printf("  ERROR [%s] 0x%08lx: got 0x%08x%08x expected 0x%08x%08x\n", t,
           (unsigned long)(DRAM_BASE + off),
           (unsigned)(got >> 32), (unsigned)got, (unsigned)(exp >> 32), (unsigned)exp);
  return 1;
}

