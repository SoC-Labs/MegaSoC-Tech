// Training mailbox: one message (16-bit, or 32-bit for streaming arguments)
static uint32_t get_mail(int mode)
{
  uint32_t mail = 0, mail_top = 0;
  if (poll_phy("training mailbox", 0x340010, 0x1, 0x0)) return 0xFF;
  apb4_read(0x3400C8, &mail);
  if (mode == 32) {
    apb4_read(0x3400D0, &mail_top);
    mail |= (mail_top << 16);
  }
  apb4_write(0x3400C4, 0);
  if (poll_phy("training mailbox ack", 0x340010, 0x1, 0x1)) return 0xFF;
  apb4_write(0x3400C4, 1);
  return mail;
}

void dwc_ddrphy_phyinit_userCustom_G_waitFwDone()
{
  uint32_t mail = 0x100;
  while (mail != 0x07) {
    mail = get_mail(16);
    printf("Training mail = 0x%08x\n", (unsigned)mail);
    if (mail == 0xFF) {
      printf("ERROR: PHY training failed\n");
      errors_total++;
      return;
    } else if (mail == 0x08) {            // streaming message
      uint32_t stream = get_mail(32);
      for (uint32_t i = 0; i < (stream & 0xFFFF); i++) (void)get_mail(32);
    }
  }
  printf("** TRAINING SUCCESSFUL **\n");
}

