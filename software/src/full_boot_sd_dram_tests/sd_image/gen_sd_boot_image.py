#!/usr/bin/env python3
#------------------------------------------------------------------------------
# Build the SD card boot image for full_boot_sd_dram_tests (MEGASOC-BOOT-006)
#
# Assembles dram_payload.S with GNU binutils (aarch64-linux-gnu-as/objcopy),
# puts a one-sector boot header in front of it and writes sd_boot_image.hex:
# one byte per line, in card order, for $readmemh in sdio_full_boot_test.sv.
#
# Card layout (512-byte sectors, starting at the image base sector):
#   sector 0      boot header, little-endian 32-bit words:
#                   [0] magic        0x4942534D ("MSBI")
#                   [1] version      1
#                   [2] load_addr_lo DRAM address to copy the payload to
#                   [3] load_addr_hi
#                   [4] size         payload size in bytes
#                   [5] entry_off    entry point offset from load_addr
#                   [6] checksum     32-bit sum of the payload words
#                   [7] hdr_check    ~(sum of words 0..6)
#   sector 1..n   payload, zero padded to whole sectors (at least
#                 --min-payload-sectors, default 2, so the loader reads it
#                 with a multi-block read, i.e. through the controller DMA,
#                 while the 1-sector header goes through the PIO path)
#
# The header values must match the loader (full_boot_sd_dram_tests.c) only
# through the header itself; the loader checks every field it reads. The base
# sector (0x3000) is the one thing fixed on both sides, plus in the bench.
#
# Usage: gen_sd_boot_image.py [--load-addr 0x80040000] [--out FILE]
# Re-run after editing dram_payload.S and commit the new hex.
#------------------------------------------------------------------------------

import argparse
import os
import struct
import subprocess
import sys
import tempfile

SECTOR = 512
MAGIC = 0x4942534D
VERSION = 1
HERE = os.path.dirname(os.path.abspath(__file__))


def assemble(src):
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "payload.o")
        binf = os.path.join(tmp, "payload.bin")
        subprocess.run(["aarch64-linux-gnu-as", "-o", obj, src], check=True)
        relocs = subprocess.run(["aarch64-linux-gnu-objdump", "-r", obj],
                                check=True, stdout=subprocess.PIPE,
                                universal_newlines=True).stdout
        if "R_AARCH64" in relocs:
            sys.exit("dram_payload.S has relocations, so it is not position "
                     "independent:\n" + relocs)
        subprocess.run(["aarch64-linux-gnu-objcopy", "-O", "binary", "-j", ".text",
                        obj, binf], check=True)
        with open(binf, "rb") as f:
            return f.read()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--src", default=os.path.join(HERE, "dram_payload.S"))
    ap.add_argument("--out", default=os.path.join(HERE, "sd_boot_image.hex"))
    ap.add_argument("--load-addr", type=lambda v: int(v, 0), default=0x80040000)
    ap.add_argument("--min-payload-sectors", type=int, default=2)
    args = ap.parse_args()

    payload = assemble(args.src)
    payload += b"\0" * (-len(payload) % 4)
    payload = payload.ljust(args.min_payload_sectors * SECTOR, b"\0")
    checksum = sum(struct.unpack("<%dI" % (len(payload) // 4), payload)) & 0xFFFFFFFF

    words = [MAGIC, VERSION, args.load_addr & 0xFFFFFFFF, args.load_addr >> 32,
             len(payload), 0, checksum]
    words.append(~sum(words) & 0xFFFFFFFF)
    header = struct.pack("<8I", *words).ljust(SECTOR, b"\0")

    image = header + payload.ljust(-(-len(payload) // SECTOR) * SECTOR, b"\0")

    with open(args.out, "w") as f:
        f.write("// SD card boot image for full_boot_sd_dram_tests (MEGASOC-BOOT-006)\n")
        f.write("// Generated by gen_sd_boot_image.py from dram_payload.S, do not edit.\n")
        f.write("// %d sectors (1 header + %d payload), payload %d bytes, load 0x%x, "
                "checksum 0x%08x\n" % (len(image) // SECTOR, len(image) // SECTOR - 1,
                                       len(payload), args.load_addr, checksum))
        for b in image:
            f.write("%02x\n" % b)

    print("wrote %s: %d sectors, payload %d bytes, load 0x%x, checksum 0x%08x"
          % (args.out, len(image) // SECTOR, len(payload), args.load_addr, checksum))


if __name__ == "__main__":
    main()
